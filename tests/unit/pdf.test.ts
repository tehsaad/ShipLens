import { describe, expect, it } from "vitest";
import { pdfText } from "@/lib/pdf/document";
import { renderMonthlySummaryPdf, type MonthlySummaryPdf } from "@/lib/pdf/monthly-summary";
import { renderWeeklyReportPdf, type WeeklyReportPdf } from "@/lib/pdf/weekly-report";
import { pdfTextOf } from "../support/pdf-text";

const generated = {
  by: "Ayesha Siddiqui",
  at: "2026-10-24 12:30",
  createdAt: new Date("2026-10-24T07:30:00Z"),
};

const weekly: WeeklyReportPdf = {
  branch: { code: "BR-KAR-001", name: "Karachi Saddar" },
  weekStart: "2026-10-12",
  weekEnd: "2026-10-18",
  status: "Approved",
  version: 4,
  submitted: { by: "Farah Khan", at: "2026-10-19 10:15" },
  approved: { by: "Bilal Ahmed", at: "2026-10-20 16:40" },
  leadNotes: "Food drive on Saturday. کراچی",
  reviewComment: "Routed on Monday.",
  totals: { collections: "2,350.00", entries: 2, newMembers: 1, activeMembers: 14 },
  collections: [
    {
      date: "2026-10-13",
      purpose: "Event",
      description: "Bake sale",
      amount: "2,500.00",
      correction: false,
      routed: "2026-10-20 09:00",
    },
    {
      date: "2026-10-14",
      purpose: "Event",
      description: "Miscounted",
      amount: "-150.00",
      correction: true,
      routed: null,
    },
  ],
  history: [
    {
      at: "2026-10-20 16:40",
      action: "Approved",
      actor: "Bilal Ahmed",
      from: "Submitted",
      to: "Approved",
      comment: "Routed on Monday.",
    },
  ],
  generated,
};

describe("PDF documents (section 7.3)", () => {
  it("prints only what the standard fonts can show", () => {
    expect(pdfText("Zoë – “quoted” €5")).toBe("Zoë – “quoted” €5");
    expect(pdfText("کراچی branch")).toBe("????? branch");
    expect(pdfText(null)).toBe("");
    expect(pdfText(42)).toBe("42");
  });

  it("renders the approved weekly report: cover, totals, collections and history", async () => {
    const pdf = await renderWeeklyReportPdf(weekly, { compress: false });
    expect(pdf.subarray(0, 5).toString()).toBe("%PDF-");
    expect(pdf.subarray(-6).toString()).toContain("%%EOF");
    const text = pdfTextOf(pdf);
    for (const expected of [
      "Weekly report BR-KAR-001",
      "2026-10-12 (Monday) to 2026-10-18 (Sunday)",
      "2026-10-20 16:40 by Bilal Ahmed",
      "2,350.00",
      "Bake sale",
      "Correction: Miscounted",
      "-150.00",
      "Not yet",
      "Submitted -> Approved",
      "Food drive on Saturday. ?????",
      "Generated by Ayesha Siddiqui on 2026-10-24 12:30 PKT",
      "Page 1 of 1",
    ]) {
      expect(text).toContain(expected);
    }
  });

  it("continues long tables on new pages and numbers every page", async () => {
    const pdf = await renderWeeklyReportPdf(
      { ...weekly, collections: Array.from({ length: 80 }, () => weekly.collections[0]!) },
      { compress: false },
    );
    const text = pdfTextOf(pdf);
    expect(text).toContain("Page 1 of 3");
    expect(text).toContain("Page 3 of 3");
  });

  it("renders the monthly branch summary", async () => {
    const summary: MonthlySummaryPdf = {
      branch: { code: "BR-LAH-001", name: "Lahore Gulberg", city: "Lahore", status: "Active" },
      month: { label: "September 2026", from: "2026-09-01", to: "2026-09-30", partial: false },
      collections: {
        total: "12,000.00",
        count: 9,
        corrections: 1,
        routed: { total: "10,000.00", count: 7 },
        unrouted: { total: "2,000.00", count: 2 },
      },
      byPurpose: [{ purpose: "General", count: 9, total: "12,000.00" }],
      members: { joined: 3, activeAtEnd: 11 },
      reports: [
        { weekStart: "2026-09-07", weekEnd: "2026-09-13", status: "Draft", collections: null },
      ],
      generated,
    };
    const text = pdfTextOf(await renderMonthlySummaryPdf(summary, { compress: false }));
    for (const expected of [
      "Monthly summary BR-LAH-001",
      "Lahore Gulberg, Lahore · September 2026",
      "2026-09-01 to 2026-09-30",
      "Routed to the main account",
      "10,000.00",
      "Joined during the month",
      "2026-09-07 to 2026-09-13",
      "Not submitted",
    ]) {
      expect(text).toContain(expected);
    }
    expect(text).not.toContain("The month is not over yet");
  });
});
