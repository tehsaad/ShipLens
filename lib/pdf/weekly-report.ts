import { PdfReport } from "@/lib/pdf/document";

/** Everything the approved weekly report PDF shows, already formatted for print. */
export type WeeklyReportPdf = {
  branch: { code: string; name: string };
  /** YYYY-MM-DD, Monday and Sunday. */
  weekStart: string;
  weekEnd: string;
  status: string;
  version: number;
  submitted: { by: string | null; at: string | null };
  approved: { by: string | null; at: string | null };
  leadNotes: string | null;
  reviewComment: string | null;
  /** Totals frozen at submission, as display strings. */
  totals: { collections: string; entries: number; newMembers: number; activeMembers: number };
  collections: {
    date: string;
    purpose: string;
    description: string | null;
    amount: string;
    correction: boolean;
    routed: string | null;
  }[];
  history: {
    at: string;
    action: string;
    actor: string | null;
    from: string | null;
    to: string | null;
    comment: string | null;
  }[];
  generated: { by: string; at: string; createdAt: Date };
};

/**
 * Approved weekly report (section 7.3): cover details, the totals frozen at submission, the
 * week's collection table and the review history from the audit log.
 */
export function renderWeeklyReportPdf(
  data: WeeklyReportPdf,
  options: { compress?: boolean } = {},
): Promise<Buffer> {
  const pdf = new PdfReport({
    title: `Weekly report ${data.branch.code}`,
    subtitle: `${data.branch.name} · week ${data.weekStart} to ${data.weekEnd}`,
    footer: `Generated by ${data.generated.by} on ${data.generated.at} PKT`,
    createdAt: data.generated.createdAt,
    compress: options.compress,
  });

  pdf.heading("Report").fields([
    ["Branch", `${data.branch.code} · ${data.branch.name}`],
    ["Week", `${data.weekStart} (Monday) to ${data.weekEnd} (Sunday)`],
    ["Status", `${data.status} (version ${data.version})`],
    ["Submitted", [data.submitted.at, data.submitted.by].filter(Boolean).join(" by ")],
    ["Approved", [data.approved.at, data.approved.by].filter(Boolean).join(" by ")],
    ["Lead notes", data.leadNotes],
    ["Review comment", data.reviewComment],
  ]);

  pdf
    .heading("Totals at submission")
    .table(
      ["Collections (net, PKR)", "Entries", "New members", "Active members"],
      [
        [
          data.totals.collections,
          data.totals.entries,
          data.totals.newMembers,
          data.totals.activeMembers,
        ],
      ],
      { right: [0, 1, 2, 3] },
    );

  pdf.heading("Collections").table(
    ["Date", "Purpose", "Description", "Amount (PKR)", "Routed"],
    data.collections.map((row) => [
      row.date,
      row.purpose,
      row.correction ? `Correction: ${row.description ?? ""}`.trim() : row.description,
      row.amount,
      row.routed ?? "Not yet",
    ]),
    { widths: [70, 70, "*", 80, 90], right: [3], empty: "No collections in this week." },
  );

  pdf.heading("Review history").table(
    ["When (PKT)", "Action", "By", "Status", "Comment"],
    data.history.map((entry) => [
      entry.at,
      entry.action,
      entry.actor,
      entry.from || entry.to ? `${entry.from ?? "-"} -> ${entry.to ?? "-"}` : null,
      entry.comment,
    ]),
    { widths: [90, 75, 90, 130, "*"] },
  );

  return pdf.toBuffer();
}
