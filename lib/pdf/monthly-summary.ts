import { PdfReport } from "@/lib/pdf/document";

/** Everything the monthly branch summary shows, already formatted for print. */
export type MonthlySummaryPdf = {
  branch: { code: string; name: string; city: string; status: string };
  /** For example "September 2026", with the first and last day as YYYY-MM-DD. */
  month: { label: string; from: string; to: string; partial: boolean };
  collections: {
    total: string;
    count: number;
    corrections: number;
    routed: { total: string; count: number };
    unrouted: { total: string; count: number };
  };
  byPurpose: { purpose: string; count: number; total: string }[];
  members: { joined: number; activeAtEnd: number };
  reports: {
    weekStart: string;
    weekEnd: string;
    status: string;
    collections: string | null;
  }[];
  generated: { by: string; at: string; createdAt: Date };
};

/**
 * Monthly branch summary (section 7.3): the month's collections (net, routed and unrouted,
 * by purpose), membership, and the weekly reports of the weeks that start in the month.
 */
export function renderMonthlySummaryPdf(
  data: MonthlySummaryPdf,
  options: { compress?: boolean } = {},
): Promise<Buffer> {
  const pdf = new PdfReport({
    title: `Monthly summary ${data.branch.code}`,
    subtitle: `${data.branch.name}, ${data.branch.city} · ${data.month.label}`,
    footer: `Generated by ${data.generated.by} on ${data.generated.at} PKT`,
    createdAt: data.generated.createdAt,
    compress: options.compress,
  });

  pdf.heading("Branch and period").fields([
    ["Branch", `${data.branch.code} · ${data.branch.name}`],
    ["City", data.branch.city],
    ["Branch status", data.branch.status],
    ["Period", `${data.month.from} to ${data.month.to}`],
  ]);
  if (data.month.partial) {
    pdf.paragraph("The month is not over yet: figures cover the days up to today.", {
      muted: true,
    });
  }

  pdf.heading("Collections").table(
    ["", "Entries", "Amount (PKR)"],
    [
      ["Net total (corrections included)", data.collections.count, data.collections.total],
      ["Routed to the main account", data.collections.routed.count, data.collections.routed.total],
      ["Not yet routed", data.collections.unrouted.count, data.collections.unrouted.total],
      ["Of which correction entries", data.collections.corrections, null],
    ],
    { widths: ["*", 80, 110], right: [1, 2] },
  );

  pdf.heading("By purpose").table(
    ["Purpose", "Entries", "Amount (PKR)"],
    data.byPurpose.map((row) => [row.purpose, row.count, row.total]),
    { widths: ["*", 80, 110], right: [1, 2], empty: "No collections in this month." },
  );

  pdf.heading("Members").table(
    ["", "Members"],
    [
      ["Joined during the month", data.members.joined],
      ["Active at the end of the period", data.members.activeAtEnd],
    ],
    { widths: ["*", 110], right: [1] },
  );

  pdf.heading("Weekly reports (weeks starting in the month)").table(
    ["Week", "Status", "Collections at submission (PKR)"],
    data.reports.map((row) => [
      `${row.weekStart} to ${row.weekEnd}`,
      row.status,
      row.collections ?? "Not submitted",
    ]),
    { widths: ["*", 100, 160], right: [2], empty: "No reports for these weeks yet." },
  );

  return pdf.toBuffer();
}
